function isCodeOrIdentifier(s: string): boolean {
  // Skip emails, URLs, currency codes (USD/MMK/THB), invoice/unit numbers (INV-001, MBR-001), pure numbers
  if (!/[a-zA-Z]/.test(s)) return true;
  if (/[@:/\\]/.test(s) && !/\s\/\s/.test(s)) return true;
  if (/^[A-Z]{2,4}$/.test(s)) return true; // ISO currency/country codes like USD, MMK, THB, UTC
  if (/^[A-Z0-9]+[-_][A-Z0-9-_]+$/i.test(s)) return true; // Codes like MBR-001, INV-2026
  return false;
}

function translateCore(text: string, lang: 'my' | 'th'): string {
  const trimmed = text.trim();
  if (!trimmed || isCodeOrIdentifier(trimmed)) return text;

  // 1. Exact or case-insensitive phrase lookup
  const exact = UI_DICTIONARY[trimmed] || NORMALIZED_MAP.get(trimmed.toLowerCase());
  if (exact) return exact[lang];

  // 2. Regex patterns
  for (const pat of REGEX_PATTERNS) {
    const m = pat.regex.exec(trimmed);
    if (m) return pat.format(m, lang);
  }

  // 3. Word-by-word compositional translation for 1–5 word UI labels/headings
  const words = trimmed.split(/\s+/);
  if (words.length >= 1 && words.length <= 5) {
    let translatedCount = 0;
    const out = words.map((w) => {
      const clean = w.replace(/^[^a-zA-Z]+|[^a-zA-Z]+$/g, '');
      if (!clean) return w;
      const wEntry = WORD_DICTIONARY[clean.toLowerCase()] || NORMALIZED_MAP.get(clean.toLowerCase());
      if (wEntry) {
        translatedCount++;
        return w.replace(clean, wEntry[lang]);
      }
      return w;
    });
    // Only use compositional translation if at least half of the words matched known UI vocabulary
    if (translatedCount > 0 && translatedCount >= Math.ceil(words.length / 2)) {
      return out.join(' ');
    }
  }

  return text;
}

export function translatePhrase(rawText: string, lang: SupportedLang): string {
  if (lang === 'en' || !rawText) return rawText;
  const trimmed = rawText.trim();
  if (!trimmed) return rawText;

  const leadingWs = rawText.slice(0, rawText.indexOf(trimmed));
  const trailingWs = rawText.slice(leadingWs.length + trimmed.length);

  // Direct match first
  const direct = UI_DICTIONARY[trimmed] || NORMALIZED_MAP.get(trimmed.toLowerCase());
  if (direct) {
    return `${leadingWs}${direct[lang]}${trailingWs}`;
  }

  // Strip decorative prefixes (+ , ← , • ) and suffixes (: , * , • , → , (count))
  const prefixMatch = /^([+←•✓✗⚠🔒🔑💡⚙️🏢]+\s*)/.exec(trimmed);
  const prefix = prefixMatch ? prefixMatch[1] : '';
  const afterPrefix = trimmed.slice(prefix.length);

  const suffixMatch = /(\s*(?::|\*|•|→|\(\d+\)|\(\d+d\)))$/.exec(afterPrefix);
  const suffix = suffixMatch ? suffixMatch[1] : '';
  const core = suffix ? afterPrefix.slice(0, afterPrefix.length - suffix.length) : afterPrefix;

  const translatedCore = translateCore(core, lang);
  if (translatedCore !== core) {
    return `${leadingWs}${prefix}${translatedCore}${suffix}${trailingWs}`;
  }

  return rawText;
}
